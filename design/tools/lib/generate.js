'use strict';
/**
 * Compiles design/tokens.xml + design/themes.xml into the gluestack / nativewind theme:
 *   - config.ts : one `colors.<theme>` record per theme, role ids as `'--<role>'` CSS variables, 'r g b' triplets;
 *   - tokens.js : the Tailwind `theme.extend` fragment (semantic colours + spacing, radii, breakpoints, type, shadow, motion).
 * Output is byte-for-byte what the former Python generator emitted (tests compare against its recorded output).
 */
const fs = require('fs');
const path = require('path');
const { parseFile, XmlError } = require('./xml');
const { NS, at, buildModel, SystemExit } = require('./registry');

const fail = (m) => {
  throw new SystemExit(m);
};

const CONFIG_HEADER = [
  '// Generated by flipova-design gen -- do not edit by hand.',
  '// Source of truth: design/tokens.xml + design/themes.xml',
  '// Regenerate with: npm run design:gen',
  "import { vars } from 'nativewind';",
  '',
];
const TOKENS_HEADER = [
  '// Generated by flipova-design gen -- do not edit by hand.',
  '// Source of truth: design/tokens.xml + design/themes.xml',
  '// Tailwind/nativewind theme, consumed by tailwind.config.js.',
  '// Regenerate with: npm run design:gen',
];

function toRgbTriplet(literal) {
  const text = literal.trim();
  if (text.startsWith('#')) {
    let d = text.slice(1);
    if (d.length === 3) d = [...d].map((c) => c + c).join('');
    if (d.length !== 6 || !/^[0-9a-fA-F]{6}$/.test(d))
      fail(`unsupported colour '${literal}' (expected #RGB or #RRGGBB)`);
    return [0, 2, 4].map((i) => parseInt(d.slice(i, i + 2), 16)).join(' ');
  }
  return text.split(/\s+/).filter(Boolean).join(' ');
}

function resolveColour(ctx, ref) {
  const raw = ref.trim();
  let parts = raw.startsWith('$ref.') ? raw.slice(5).split('.') : raw.split('.');
  if (parts.length && ctx.registers.includes(parts[0])) parts = parts.slice(1);
  if (parts.length < 2) fail(`dangling reference '${ref}' (expected $ref.<register>.<id>.<path>)`);
  const values = ctx.tokenValues.get(parts[0]);
  const key = parts.slice(1).join('.');
  if (!values || !values.has(key)) fail(`dangling reference '${ref}': no token value matches`);
  return values.get(key);
}

function catalog(man, name) {
  const file = man.ctx.catalogFiles.get(name);
  if (!file || !fs.existsSync(file)) fail(`manifest: no ${name} catalog file found`);
  return parseFile(file);
}

/** [[themeId, [[roleId, 'r g b'], ...]], ...] in themes.xml order. */
function themeRoleColours(man) {
  const root = catalog(man, 'themes');
  return at(root, 'items', 'theme').map((theme) => {
    const tid = (theme.get('id') || '').trim();
    const roles = at(theme, 'roleMap', 'role').map((role) => {
      const rid = (role.get('id') || '').trim();
      const ref = role.find('ref', NS);
      const val = role.find('value', NS);
      let literal;
      if (ref) literal = resolveColour(man.ctx, ref.text || '');
      else if (val) literal = val.text || '';
      else fail(`theme '${tid}': role '${rid}' needs a <ref> or a <value>`);
      return [rid, toRgbTriplet(literal)];
    });
    return [tid, roles];
  });
}

function themeRoleIds(man, warn = console.log) {
  const themes = themeRoleColours(man);
  if (!themes.length) return [];
  const reference = themes[0][1].map(([r]) => r);
  for (const [tid, roles] of themes.slice(1)) {
    const others = roles.map(([r]) => r);
    if (others.length !== reference.length || others.some((r, i) => r !== reference[i])) {
      warn(
        `warning: theme '${tid}' declares a different role set than '${themes[0][0]}' (Tailwind colours are generated from '${themes[0][0]}')`,
      );
    }
  }
  return reference;
}

const JS_IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const jsKey = (name) => (JS_IDENT.test(name) ? name : `'${name.replace(/'/g, "\\'")}'`);

function themeVariants(man) {
  return at(catalog(man, 'themes'), 'items', 'theme').map((t) => [
    (t.get('variant') || 'default').trim() || 'default',
    (t.get('mode') || '').trim(),
    (t.get('id') || '').trim(),
  ]);
}

const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

function renderVariantTable(variants) {
  const ordered = new Map();
  for (const [variant, mode, tid] of variants) {
    if (!ordered.has(variant)) ordered.set(variant, []);
    const entries = ordered.get(variant);
    if (entries.some(([m]) => m === mode)) {
      fail(
        `theme variant '${variant}' declares the mode '${mode}' twice: a variant is a light/dark pair, so it has exactly one theme per mode`,
      );
    }
    entries.push([mode, tid]);
  }
  const lines = ['export const variants = {'];
  for (const variant of [...ordered.keys()].sort(cmp)) {
    const pairs = [...ordered.get(variant)]
      .sort((a, b) => cmp(a[0], b[0]) || cmp(a[1], b[1]))
      .map(([m, t]) => `${jsKey(m)}: '${t}'`)
      .join(', ');
    lines.push(`  ${jsKey(variant)}: { ${pairs} },`);
  }
  lines.push('};');
  return lines;
}

function renderGluestackConfig(man) {
  const themes = themeRoleColours(man);
  const lines = [...CONFIG_HEADER];
  lines.push('// Raw color values (space-separated RGB) - edit design/themes.xml and regenerate');
  lines.push('export const colors = {');
  for (const [tid, roles] of themes) {
    lines.push(`  ${jsKey(tid)}: {`);
    for (const [rid, triplet] of roles) lines.push(`    '--${rid}': '${triplet}',`);
    lines.push('  },');
  }
  lines.push('};', '', '// Config for nativewind vars() - used by the provider', 'export const config = {');
  for (const [tid] of themes) lines.push(`  ${jsKey(tid)}: vars(colors['${tid}']),`);
  lines.push('};', '');
  lines.push('// Theme variants: variant -> mode -> theme id, from the `variant` attribute in');
  lines.push('// design/themes.xml. `default` holds the base light/dark pair.');
  lines.push(...renderVariantTable(themeVariants(man)));
  return `${lines.join('\n')}\n`;
}

// --- tokens.js -------------------------------------------------------------------------------------------------

const jsStr = (v) => `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const text = (el) => (el ? (el.text || '').trim() : '');
const valuesOf = (token) => at(token, 'values', 'value');
const scaled = (values, unit, def = 'px') => values.map((v) => [v.get('id') || '', jsStr(`${text(v)}${unit || def}`)]);
const plain = (values) => values.map((v) => [v.get('id') || '', jsStr(text(v))]);

/** Python's float() accepts these forms; anything else is a plain string. */
function asFloat(raw) {
  const s = raw.trim();
  if (!/^[+-]?(\d+(\.\d*)?|\.\d+)([eE][+-]?\d+)?$/.test(s)) return null;
  return Number(s);
}

function shadowEntries(ctx, values) {
  return values.map((v) => {
    const ref = at(v, 'color', 'ref')[0];
    const hex = ref ? resolveColour(ctx, text(ref)) : '#000000';
    const rgb = toRgbTriplet(hex);
    const x = text(at(v, 'offset', 'x')[0]) || '0';
    const y = text(at(v, 'offset', 'y')[0]) || '0';
    const radius = text(v.find('radius', NS)) || '0';
    const opacity = text(v.find('opacity', NS)) || '1';
    return [v.get('id') || '', jsStr(`${x}px ${y}px ${radius}px rgb(${rgb} / ${opacity})`)];
  });
}

function entry(ctx, token) {
  const tid = (token.get('id') || '').trim();
  const unit = (token.get('unit') || '').trim();
  const values = valuesOf(token);
  switch (tid) {
    case 'spacing':
      return ['spacing', scaled(values, unit)];
    case 'radii':
      return ['borderRadius', scaled(values, unit)];
    case 'breakpoints':
      return ['screens', scaled(values, unit)];
    case 'family':
      return [
        'fontFamily',
        values.map((v) => {
          const fams = text(v.find('web', NS))
            .split(',')
            .map((p) => p.trim())
            .filter(Boolean);
          return [v.get('id') || '', `[${fams.map(jsStr).join(', ')}]`];
        }),
      ];
    case 'fontSizes':
      return ['fontSize', scaled(values, unit)];
    case 'fontWeights':
      return ['fontWeight', plain(values)];
    case 'lineHeights':
      return [
        'lineHeight',
        values.map((v) => {
          const raw = text(v);
          const n = asFloat(raw);
          const expr = n === null ? jsStr(raw) : jsStr(n <= 2 ? raw : `${raw}${unit || 'px'}`);
          return [v.get('id') || '', expr];
        }),
      ];
    case 'letterSpacings':
      return ['letterSpacing', scaled(values, unit, 'em')];
    case 'shadow':
      return ['boxShadow', shadowEntries(ctx, values)];
    case 'zIndex':
      return ['zIndex', plain(values)];
    case 'opacity':
      return ['opacity', plain(values)];
    case 'duration':
      return ['transitionDuration', scaled(values, unit || 'ms', 'ms')];
    case 'easing':
      return [
        'transitionTimingFunction',
        values.flatMap((v) => {
          const web = text(v.find('web', NS));
          return !web || web === 'spring' ? [] : [[v.get('id') || '', jsStr(web)]];
        }),
      ];
    default:
      return null; // `color` (palette) is internal: semantic colours live in config.ts
  }
}

function renderTokensTheme(man) {
  const root = catalog(man, 'tokens');
  const groups = [];
  const roles = themeRoleIds(man, man.warn);
  if (roles.length) groups.push(['colors', roles.map((rid) => [rid, jsStr(`rgb(var(--${rid})/<alpha-value>)`)])]);
  for (const token of at(root, 'items', 'token')) {
    const e = entry(man.ctx, token);
    if (e) groups.push(e);
  }
  const lines = [...TOKENS_HEADER, 'module.exports = {', '  theme: {'];
  for (const [key, items] of groups) {
    lines.push(`    ${key}: {`);
    for (const [ident, expr] of items) lines.push(`      ${jsStr(ident)}: ${expr},`);
    lines.push('    },');
  }
  lines.push('  },', '};');
  return `${lines.join('\n')}\n`;
}

// --- design-theme.ts: the provider-neutral theme ------------------------------------------------------------------

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const hex = (triplet) =>
  `#${triplet
    .split(' ')
    .map((n) => Number(n).toString(16).padStart(2, '0'))
    .join('')}`;
const num = (raw) => {
  const n = asFloat(raw);
  return n === null ? raw.trim() : n;
};
const q = (s) => JSON.stringify(s);

/**
 * Every value a provider adapter needs, resolved: colours as '#rrggbb' per theme (keys camelCased from the roles),
 * scales as numbers. Adapters (Paper, Tamagui, Reusables, gluestack) map this one object, which is what keeps their
 * design identical. Deterministic output.
 */
function renderDesignTheme(man) {
  const themesRoot = catalog(man, 'themes');
  const tokensRoot = catalog(man, 'tokens');
  const themes = at(themesRoot, 'items', 'theme');
  const lines = [
    '// Generated by flipova-design gen -- do not edit by hand.',
    '// Source of truth: design/tokens.xml + design/themes.xml',
    '// Provider-neutral theme: every provider adapter reads this one object.',
    '// Regenerate with: npm run design:gen',
    '',
    'export const designTheme = {',
    '  themes: {',
  ];
  const colours = new Map(themeRoleColours(man));
  for (const t of themes) {
    const id = (t.get('id') || '').trim();
    lines.push(`    ${q(id)}: {`);
    lines.push(`      mode: ${q((t.get('mode') || '').trim())},`);
    lines.push(`      variant: ${q((t.get('variant') || 'default').trim() || 'default')},`);
    lines.push('      colors: {');
    for (const [rid, triplet] of colours.get(id)) lines.push(`        ${q(camel(rid))}: ${q(hex(triplet))},`);
    lines.push('      },', '    },');
  }
  lines.push('  },', '  variants: {');
  const variants = new Map();
  for (const [v, mode, tid] of themeVariants(man)) {
    if (!variants.has(v)) variants.set(v, []);
    variants.get(v).push([mode, tid]);
  }
  for (const v of [...variants.keys()].sort(cmp)) {
    lines.push(
      `    ${q(v)}: { ${variants
        .get(v)
        .sort((a, b) => cmp(a[0], b[0]))
        .map(([m, t]) => `${q(m)}: ${q(t)}`)
        .join(', ')} },`,
    );
  }
  lines.push('  },', '  scale: {');
  const scales = {
    spacing: 'spacing',
    radii: 'radii',
    fontSizes: 'fontSizes',
    fontWeights: 'fontWeights',
    lineHeights: 'lineHeights',
    letterSpacings: 'letterSpacings',
    opacity: 'opacity',
    duration: 'duration',
    zIndex: 'zIndex',
    breakpoints: 'breakpoints',
  };
  const tokens = new Map(at(tokensRoot, 'items', 'token').map((t) => [t.get('id'), t]));
  for (const [key, id] of Object.entries(scales)) {
    const token = tokens.get(id);
    if (!token) continue;
    lines.push(`    ${key}: {`);
    for (const v of valuesOf(token))
      lines.push(`      ${q(v.get('id'))}: ${typeof num(text(v)) === 'number' ? num(text(v)) : q(text(v))},`);
    lines.push('    },');
  }
  const fam = tokens.get('family');
  if (fam) {
    lines.push('    fontFamilies: {');
    for (const v of valuesOf(fam))
      lines.push(
        `      ${q(v.get('id'))}: { native: ${q(text(v.find('native', NS)))}, web: ${q(text(v.find('web', NS)))} },`,
      );
    lines.push('    },');
  }
  const shadow = tokens.get('shadow');
  if (shadow) {
    lines.push('    shadows: {');
    for (const v of valuesOf(shadow)) {
      const ref = at(v, 'color', 'ref')[0];
      const colour = hex(toRgbTriplet(ref ? resolveColour(man.ctx, text(ref)) : '#000000'));
      lines.push(
        `      ${q(v.get('id'))}: { color: ${q(colour)}, offsetX: ${num(text(at(v, 'offset', 'x')[0]) || '0')}, offsetY: ${num(text(at(v, 'offset', 'y')[0]) || '0')}, radius: ${num(text(v.find('radius', NS)) || '0')}, opacity: ${num(text(v.find('opacity', NS)) || '1')}, elevation: ${num(text(v.find('elevation', NS)) || '0')} },`,
      );
    }
    lines.push('    },');
  }
  lines.push(
    '  },',
    '} as const;',
    '',
    'export type DesignTheme = typeof designTheme;',
    'export type ThemeId = keyof typeof designTheme.themes;',
    "export type ColorRole = keyof (typeof designTheme.themes)[ThemeId]['colors'];",
    '',
  );
  return lines.join('\n');
}

// --- manifest ----------------------------------------------------------------------------------------------------

function loadManifest(root, manifestPath) {
  const mroot = parseFile(manifestPath);
  const pipeline = at(mroot, 'meta', 'pipeline')[0];
  if (!pipeline) fail('manifest: missing meta/pipeline');
  const outputsEl = pipeline.find('outputs', NS);
  if (!outputsEl) fail('manifest: missing meta/pipeline/outputs');
  const outputs = {};
  for (const c of outputsEl.children) outputs[c.name] = (c.text || '').trim();
  const schemaPath = path.join(path.dirname(path.resolve(manifestPath)), 'schema.xsd');
  if (!fs.existsSync(schemaPath)) fail('schema.xsd not found next to the manifest');
  return {
    root: path.resolve(root),
    manifestPath: path.resolve(manifestPath),
    schemaPath,
    outputs,
    ctx: buildModel(root, manifestPath),
  };
}

const RENDERERS = {
  gluestackConfig: renderGluestackConfig,
  gluestackTokens: renderTokensTheme,
  designTheme: renderDesignTheme,
};

function targets(man) {
  const list = [];
  for (const [kind, rel] of Object.entries(man.outputs)) {
    const render = RENDERERS[kind];
    if (!render) throw Object.assign(new Error(`manifest output '${kind}' has no generator`), { exit: 2 });
    if (!rel) throw Object.assign(new Error(`manifest output '${kind}' has an empty path`), { exit: 2 });
    list.push([path.resolve(man.root, rel), render(man)]);
  }
  if (!list.length) throw Object.assign(new Error('manifest declares no outputs'), { exit: 2 });
  return list;
}

/** CLI: `gen [--check] [--list]`. Returns the exit code. */
function run({ root, manifest, check = false, list = false, out = console.log, err = console.error }) {
  let man;
  try {
    man = loadManifest(root, manifest);
    man.warn = out;
    if (list) {
      for (const [tid, roles] of themeRoleColours(man)) {
        out(`${tid} (${roles.length} role(s))`);
        for (const [rid, triplet] of roles) out(`  --${rid}: ${triplet}`);
      }
      return 0;
    }
    let drift = 0;
    for (const [target, content] of targets(man)) {
      if (check) {
        const exists = fs.existsSync(target);
        if (!exists || fs.readFileSync(target, 'utf8') !== content) {
          out(exists ? `changed ${target}` : `missing ${target}`);
          drift++;
        }
      } else {
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.writeFileSync(target, content, 'utf8');
        out(`written ${target}`);
      }
    }
    if (check) {
      if (drift) return 1;
      out('up to date');
    }
    return 0;
  } catch (e) {
    if (e instanceof XmlError) {
      err(`error: ${e.file ? `${e.file}:${e.line}: ` : ''}malformed XML: ${e.message}`);
      return 1;
    }
    if (e instanceof SystemExit) {
      err(e.message);
      return 1;
    }
    if (e.exit) {
      err(`error: ${e.message}`);
      return e.exit;
    }
    throw e;
  }
}

